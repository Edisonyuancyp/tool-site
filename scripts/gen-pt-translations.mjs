// ── Generator ──────────────────────────────────────────────────────────────
const tools = fs.readdirSync(REGISTRY).filter(d => {
  return fs.existsSync(path.join(REGISTRY, d, "meta.es.json"));
});

let created = 0, skipped = 0;

for (const slug of tools) {
  const outPath = path.join(REGISTRY, slug, "meta.pt.json");
  if (fs.existsSync(outPath)) { skipped++; continue; }

  const metaPath = path.join(REGISTRY, slug, "meta.json");
  if (!fs.existsSync(metaPath)) continue;
  const meta = JSON.parse(fs.readFileSync(metaPath, "utf8"));

  const pt = PT[slug];
  if (!pt) {
    console.log(`  ⚠ No PT translation for: ${slug}`);
    continue;
  }

  const output = {
    slug,
    name: pt.name,
    tagline: pt.tagline,
    description: meta.description,
    metaTitle: pt.metaTitle,
    metaDescription: pt.metaDesc,
    keywords: pt.keywords,
    category: CAT_PT[meta.category] ?? meta.category,
    icon: meta.icon,
    faqs: pt.faqs.map(f => ({ question: f.q, answer: f.a })),
    relatedTools: meta.relatedTools ?? [],
    variants: pt.variants,
  };

  fs.writeFileSync(outPath, JSON.stringify(output, null, 2), "utf8");
  console.log(`  ✓ ${slug}/meta.pt.json`);
  created++;
}

console.log(`\nDone: ${created} created, ${skipped} skipped.`);
